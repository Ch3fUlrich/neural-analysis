def _collect_plot_specs(
    activity: npt.NDArray[np.float64],
    metadata: dict[str, Any],
    colors: list[str],
    cell_types: list[str] | None,
    n_example_cells: int,
    show_raster: bool,
    show_fields: bool,
    show_behavior: bool,
    show_ground_truth: bool,
    show_embeddings: bool,
    embedding_methods: list[str],
    n_embedding_dims: int,
    max_raster_cells: int,
) -> tuple[
    list[PlotSpec],
    list[PlotSpec],
    list[PlotSpec],
    list[PlotSpec],
    list[PlotSpec],
    list[PlotSpec],
]:
    """Collect all plot specs without assigning positions.

    Returns:
        Tuple of (raster_specs, coverage_specs, example_cell_specs,
                  behavior_specs, ground_truth_specs, embedding_specs)
    """
    raster_specs: list[PlotSpec] = []
    coverage_specs: list[PlotSpec] = []
    example_cell_specs: list[PlotSpec] = []
    behavior_specs: list[PlotSpec] = []
    ground_truth_specs: list[PlotSpec] = []
    embedding_specs: list[PlotSpec] = []

    # 1. Raster plot
    if show_raster:
        raster_spec = _create_raster_plot(
            activity,
            colors,
            max_cells=max_raster_cells,
            subplot_position=0,  # Temporary position
            cell_types=cell_types,
        )
        raster_specs.append(raster_spec)

    # 2. Collect coverage and example cells
    if show_fields:
        # Check if this is a mixed population
        if cell_types is not None:
            # Mixed population: plot each cell type separately
            cell_indices_dict = metadata.get("cell_indices", {})

            for cell_type_name, cell_idxs in cell_indices_dict.items():
                # Extract activity for this cell type
                type_activity = activity[:, cell_idxs]
                type_colors = [colors[i] for i in cell_idxs]

                # Create a temporary metadata dict for this cell type
                type_metadata = metadata.copy()
                type_metadata["cell_type"] = cell_type_name

                # Slice cell-specific metadata arrays for this cell type
                pref_dirs = metadata.get("preferred_directions")
                if pref_dirs is not None:
                    type_metadata["preferred_directions"] = pref_dirs[cell_idxs]

                field_ctrs = metadata.get("field_centers")
                if field_ctrs is not None:
                    type_metadata["field_centers"] = field_ctrs[cell_idxs]

                # Add coverage maps for place/grid cells FIRST
                if cell_type_name in ("place", "grid"):
                    n_dims = metadata.get("n_dims", 2)
                    coverage_spec: PlotSpec | list[PlotSpec] | None
                    if n_dims == 1:
                        coverage_spec = _create_coverage_histogram_1d(
                            type_activity, type_metadata, 0
                        )
                    elif n_dims == 2:
                        coverage_spec = _create_coverage_heatmap(
                            type_activity, type_metadata, 0
                        )
                    elif n_dims == 3:
                        coverage_spec = _create_coverage_heatmap_3d(
                            type_activity, type_metadata, 0
                        )
                    else:
                        coverage_spec = None

                    if coverage_spec is not None:
                        if isinstance(coverage_spec, list):
                            coverage_specs.extend(coverage_spec)
                        else:
                            coverage_specs.append(coverage_spec)

                # Generate example cell plots for this cell type
                type_specs = _create_field_plots(
                    type_activity, type_metadata, type_colors, 0, n_example_cells
                )
                if type_specs:
                    example_cell_specs.extend(type_specs)

                # Add example cell heatmaps (only for 1D and 2D, not 3D)
                # Grid cells: add here; place cells: already in field_plots
                if cell_type_name in ("place", "grid"):
                    n_dims = metadata.get("n_dims", 2)
                    if n_dims in (1, 2) and cell_type_name == "grid":
                        example_specs = _create_grid_example_cells(
                            type_activity,
                            type_metadata,
                            [CELL_TYPE_COLORS["grid"]] * n_example_cells,
                            0,
                            n_example_cells,
                        )
                        if example_specs:
                            example_cell_specs.extend(example_specs)
        else:
            # Single cell type
            # Add coverage heatmap FIRST for place/grid cells (1D, 2D, and 3D)
            # OR add diagnostic plots for random cells
            cell_type = metadata.get("cell_type")
            if cell_type in ("place", "grid"):
                n_dims = metadata.get("n_dims", 2)
                coverage_spec_local: PlotSpec | list[PlotSpec] | None
                if n_dims == 1:
                    coverage_spec_local = _create_coverage_histogram_1d(
                        activity, metadata, subplot_position=0
                    )
                elif n_dims == 2:
                    coverage_spec_local = _create_coverage_heatmap(
                        activity, metadata, subplot_position=0
                    )
                elif n_dims == 3:
                    coverage_spec_local = _create_coverage_heatmap_3d(
                        activity, metadata, subplot_position=0
                    )
                else:
                    coverage_spec_local = None

                if coverage_spec_local is not None:
                    if isinstance(coverage_spec_local, list):
                        coverage_specs.extend(coverage_spec_local)
                    else:
                        coverage_specs.append(coverage_spec_local)
            elif cell_type == "random":
                # For random cells: add 4 diagnostic plots to verify
                # lack of spatial/directional structure
                diagnostic_specs = _create_random_diagnostics(
                    activity, metadata, subplot_position=0
                )
                if diagnostic_specs:
                    coverage_specs.extend(diagnostic_specs)

            # Then add example cell plots
            field_specs = _create_field_plots(
                activity,
                metadata,
                colors,
                subplot_position=0,
                n_examples=n_example_cells,
            )
            if field_specs:
                example_cell_specs.extend(field_specs)

            # Add example cell heatmaps AFTER coverage
            # Grid cells: add example cells here (not in field_specs)
            # Place cells: already added in _create_place_field_plots
            if cell_type in ("place", "grid"):
                n_dims = metadata.get("n_dims", 2)
                if n_dims in (1, 2) and cell_type == "grid":
                    # Grid cells: add variable number of example rate maps
                    example_specs = _create_grid_example_cells(
                        activity,
                        metadata,
                        [CELL_TYPE_COLORS["grid"]] * n_example_cells,
                        0,
                        n_example_cells,
                    )
                    if example_specs:
                        example_cell_specs.extend(example_specs)

    # 3. Behavioral trajectory
    if show_behavior and "positions" in metadata:
        behavior_spec = _create_behavior_plot(
            metadata["positions"], metadata, subplot_position=0
        )
        if behavior_spec:
            if isinstance(behavior_spec, list):
                behavior_specs.extend(behavior_spec)
            else:
                behavior_specs.append(behavior_spec)

    # 4. Ground truth embedding
    if show_ground_truth and "ground_truth_embedding" in metadata:
        gt_spec = _create_ground_truth_plot(metadata, subplot_position=0)
        if gt_spec:
            ground_truth_specs.append(gt_spec)

    # 5. Learned embeddings
    if show_embeddings:
        emb_specs = _create_embedding_plots(
            activity,
            metadata,
            embedding_methods,
            n_embedding_dims,
            subplot_position=0,
        )
        embedding_specs.extend(emb_specs)

    return (
        raster_specs,
        coverage_specs,
        example_cell_specs,
        behavior_specs,
        ground_truth_specs,
        embedding_specs,
    )


def _assign_subplot_positions_mixed(
    raster_specs: list[PlotSpec],
    coverage_specs: list[PlotSpec],
    example_cell_specs: list[PlotSpec],
    ground_truth_specs: list[PlotSpec],
    behavior_specs: list[PlotSpec],
    embedding_specs: list[PlotSpec],
) -> tuple[list[PlotSpec], int, int]:
    """Assign subplot positions for mixed populations.

    Returns:
        Tuple of (plot_specs, nrows, ncols)
    """
    import math

    # Count required plots: raster + coverage(s) + ground_truth
    # Behavior and embeddings are reserved for last 3 positions
    n_required = len(raster_specs) + len(coverage_specs) + len(ground_truth_specs)
    n_reserved = len(behavior_specs) + len(
        embedding_specs
    )  # Should be 3 (behavior + PCA + UMAP)

    # Try different grid sizes to find one that fits well
    best_grid = None
    best_n_examples = 0
    min_empty = float("inf")

    for ncols in [3, 4, 5]:
        # Calculate how many example cells we can fit
        total_needed = n_required + n_reserved
        grid_size = ncols * math.ceil(total_needed / ncols)
        nrows = math.ceil(grid_size / ncols)
        grid_size = nrows * ncols

        # Available positions for example cells
        available_for_examples = grid_size - total_needed
        if available_for_examples < 0:
            available_for_examples = 0

        n_empty = (
            grid_size
            - total_needed
            - min(available_for_examples, len(example_cell_specs))
        )

        if n_empty < min_empty and available_for_examples >= 0:
            min_empty = n_empty
            best_grid = (nrows, ncols)
            best_n_examples = min(available_for_examples, len(example_cell_specs))

    if best_grid is None:
        # Fallback to default calculation
        ncols = 3
        total_needed = n_required + n_reserved
        nrows = math.ceil(total_needed / ncols)
        grid_size = nrows * ncols
        best_n_examples = min(len(example_cell_specs), max(0, grid_size - total_needed))
    else:
        nrows, ncols = best_grid
        grid_size = nrows * ncols

    # Now assign positions: raster -> coverage -> example cells -> ground_truth -> [last 3: behavior, PCA, UMAP]
    plot_specs: list[PlotSpec] = []

    # Add raster (first subplot)
    for spec in raster_specs:
        spec.subplot_position = len(plot_specs)
        plot_specs.append(spec)

    # Add coverage
    for spec in coverage_specs:
        spec.subplot_position = len(plot_specs)
        plot_specs.append(spec)

    # Add example cells (fill middle subplots up to best_n_examples)
    for _i, spec in enumerate(example_cell_specs[:best_n_examples]):
        spec.subplot_position = len(plot_specs)
        plot_specs.append(spec)

    # Add ground truth if present
    for spec in ground_truth_specs:
        spec.subplot_position = len(plot_specs)
        plot_specs.append(spec)

    # Reserve last 3 positions for behavior + embeddings
    last_row_start = grid_size - 3
    behavior_pos = last_row_start
    embedding_positions = [last_row_start + 1, last_row_start + 2]

    # Add behavior (second to last position)
    for spec in behavior_specs:
        spec.subplot_position = behavior_pos
        plot_specs.append(spec)

    # Add embeddings (last 2 positions: PCA, UMAP)
    for i, spec in enumerate(embedding_specs):
        if i < len(embedding_positions):
            spec.subplot_position = embedding_positions[i]
            plot_specs.append(spec)

    return plot_specs, nrows, ncols


def _assign_subplot_positions_single(
    raster_specs: list[PlotSpec],
    coverage_specs: list[PlotSpec],
    example_cell_specs: list[PlotSpec],
    ground_truth_specs: list[PlotSpec],
    behavior_specs: list[PlotSpec],
    embedding_specs: list[PlotSpec],
    n_example_cells: int,
) -> tuple[list[PlotSpec], int, int]:
    """Assign subplot positions for single cell type.

    Returns:
        Tuple of (plot_specs, nrows, ncols)
    """
    import math

    plot_specs = []
    n_plots = 0

    # Add raster (first subplot)
    for spec in raster_specs:
        spec.subplot_position = n_plots
        plot_specs.append(spec)
        n_plots += 1

    # Add coverage (second subplot)
    for spec in coverage_specs:
        spec.subplot_position = n_plots
        plot_specs.append(spec)
        n_plots += 1

    # Add example cells (middle subplots) - limit to n_example_cells
    for i, spec in enumerate(example_cell_specs):
        if i >= n_example_cells:
            break  # Only add up to n_example_cells
        spec.subplot_position = n_plots
        plot_specs.append(spec)
        n_plots += 1

    # Add ground truth if present (before last row)
    for spec in ground_truth_specs:
        spec.subplot_position = n_plots
        plot_specs.append(spec)
        n_plots += 1

    # Add last row (behavior + embeddings)
    for spec in behavior_specs:
        spec.subplot_position = n_plots
        plot_specs.append(spec)
        n_plots += 1

    for spec in embedding_specs:
        spec.subplot_position = n_plots
        plot_specs.append(spec)
        n_plots += 1

    # Compute optimal grid layout (minimize empty subplots)
    if n_plots <= 2:
        nrows, ncols = 1, n_plots
    elif n_plots <= 4:
        nrows, ncols = 2, 2
    elif n_plots <= 6:
        nrows, ncols = 2, 3
    else:
        # For more plots, use a more efficient layout
        ncols = min(3, n_plots)
        nrows = math.ceil(n_plots / ncols)

    return plot_specs, nrows, ncols


def _create_and_render_grid(
    plot_specs: list[PlotSpec],
    nrows: int,
    ncols: int,
    cell_type: str,
    cell_types: list[str] | None,
    figsize: tuple[float, float] | None,
    backend: str,
) -> Figure:
    """Create and render the final plot grid."""
    if len(plot_specs) == 0:
        raise ValueError("No plots to show. Enable at least one plot type.")

    from neural_analysis.plotting.core import PlotConfig
    from neural_analysis.plotting.grid_config import GridLayoutConfig

    grid = PlotGrid(
        plot_specs=plot_specs,
        config=PlotConfig(
            figsize=(
                int((figsize or (ncols * 5, nrows * 4))[0]),
                int((figsize or (ncols * 5, nrows * 4))[1]),
            )
        ),
        layout=GridLayoutConfig(
            rows=nrows,
            cols=ncols,
            vertical_spacing=0.35,
            horizontal_spacing=0.25,
        ),
        backend=cast('Literal["matplotlib", "plotly"]', backend),
    )

    result = grid.plot()
    # For matplotlib, grid.plot() returns (fig, axes); for plotly, just fig
    if backend == "matplotlib":
        fig, _ = result  # Unpack tuple
    else:
        fig = result

    # Add overall title with proper spacing
    title = f"Synthetic Neural Data: {cell_type.title()} Cells"
    if cell_types is not None:
        unique_types = sorted(set(cell_types))
        title = f"Synthetic Neural Data: Mixed Population ({', '.join(unique_types)})"

    if backend == "matplotlib":
        # Adjust suptitle position to avoid overlap
        fig.suptitle(title, fontsize=14, y=0.995)
        # Adjust subplot spacing to prevent overlap
        fig.tight_layout(rect=[0, 0, 1, 0.98])
    else:
        fig.update_layout(title_text=title)

    return fig  # type: ignore[no-any-return]


def plot_synthetic_data(
    activity: npt.NDArray[np.float64],
    metadata: dict[str, Any],
    show_raster: bool = True,
    show_fields: bool = True,
    show_behavior: bool = True,
    show_ground_truth: bool = True,
    show_embeddings: bool = True,
    embedding_methods: list[str] | None = None,
    n_embedding_dims: int = 2,
    max_raster_cells: int = 100,
    figsize: tuple[float, float] | None = None,
    backend: str = "matplotlib",
) -> Figure:
    """Plot comprehensive visualization of synthetic neural data.

    Creates a multi-panel figure showing:
    - Raster plot of neural activity (color-coded by cell type)
    - Place fields or tuning curves (if applicable)
    - Behavioral trajectory
    - Ground truth embedding (ring/torus if available)
    - Learned embeddings (PCA, UMAP, etc.)

    Args:
        activity: Neural activity matrix, shape (n_samples, n_cells).
        metadata: Dictionary with dataset metadata (positions, cell_type, etc.).
        show_raster: Show neural activity raster plot.
        show_fields: Show place fields or tuning curves.
        show_behavior: Show behavioral trajectory.
        show_ground_truth: Show ground truth embedding (if available).
        show_embeddings: Show learned embeddings.
        embedding_methods: List of embedding methods ('pca', 'umap', 'tsne', etc.).
        n_embedding_dims: Dimensionality of embeddings (2 or 3).
        max_raster_cells: Maximum number of cells to show in raster.
        figsize: Figure size as (width, height).
        backend: 'matplotlib' or 'plotly'.

    Returns:
        fig: Matplotlib figure or Plotly figure object.

    Examples:
        >>> from neural_analysis.data.synthetic_data import generate_place_cells
        >>> activity, meta = generate_place_cells(50, 1000, plot=True)
        # This automatically calls plot_synthetic_data internally

        >>> # Or plot manually
        >>> activity, meta = generate_place_cells(50, 1000, plot=False)
        >>> fig = plot_synthetic_data(activity, meta)
    """
    if embedding_methods is None:
        embedding_methods = ["pca", "umap"]

    # Determine cell types and colors
    cell_type, cell_types, colors = _get_cell_colors(activity, metadata)

    # Count fixed plots and calculate optimal example cells
    n_fixed_plots = _count_fixed_plots(
        metadata,
        show_raster,
        show_fields,
        show_behavior,
        show_ground_truth,
        show_embeddings,
        embedding_methods,
    )
    n_example_cells = _calculate_optimal_example_cells(n_fixed_plots, cell_type)

    # Collect all plot specs
    (
        raster_specs,
        coverage_specs,
        example_cell_specs,
        behavior_specs,
        ground_truth_specs,
        embedding_specs,
    ) = _collect_plot_specs(
        activity,
        metadata,
        colors,
        cell_types,
        n_example_cells,
        show_raster,
        show_fields,
        show_behavior,
        show_ground_truth,
        show_embeddings,
        embedding_methods,
        n_embedding_dims,
        max_raster_cells,
    )

    # Assign subplot positions based on population type
    if cell_types is not None:
        plot_specs, nrows, ncols = _assign_subplot_positions_mixed(
            raster_specs,
            coverage_specs,
            example_cell_specs,
            ground_truth_specs,
            behavior_specs,
            embedding_specs,
        )
    else:
        plot_specs, nrows, ncols = _assign_subplot_positions_single(
            raster_specs,
            coverage_specs,
            example_cell_specs,
            ground_truth_specs,
            behavior_specs,
            embedding_specs,
            n_example_cells,
        )

    # Create and render the grid
    return _create_and_render_grid(
        plot_specs, nrows, ncols, cell_type, cell_types, figsize, backend
    )


